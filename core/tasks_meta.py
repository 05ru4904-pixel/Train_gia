# Буквы для вариантов ответа. Порядок фиксирован: индекс варианта -> буква.
# Ё пропущена намеренно — в бланках ЕГЭ и в шаблоне админ-бота её нет.
OPTION_LETTERS = "АБВГДЕЖЗИКЛМНОПРСТУФХЦЧШЩЭЮЯ"


def title(number: int) -> str:
    return TASKS.get(number, ("Задание", ""))[0]


def subtitle(number: int) -> str:
    return TASKS.get(number, ("", ""))[1]


def letter(index: int) -> str:
    """Индекс варианта (0-based) -> буква. За пределами алфавита — номер."""
    if 0 <= index < len(OPTION_LETTERS):
        return OPTION_LETTERS[index]
    return str(index + 1)


def letter_index(char: str) -> int:
    """Буква -> индекс варианта. -1, если буква неизвестна."""
    return OPTION_LETTERS.find(char.upper().strip())


def is_valid_number(number: int) -> bool:
    return FIRST_TASK <= number <= LAST_TASK
