# условие. Поэтому парсер сырых вариантов берёт вид отсюда и не гадает по тексту.
#
# Без этой таблицы возвращаются две ловушки, на которых спотыкались и парсер, и
# модели: у №21 материал начинается с «1)», «2)» и выглядит как варианты ответа,
