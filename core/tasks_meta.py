#
# Поменяет ФИПИ структуру работы — правится только этот блок.
KIND_BY_NUMBER: dict[int, str] = {}
for _n in (1, 5, 6, 7, 25):
    KIND_BY_NUMBER[_n] = KIND_OPEN
for _n in (2, 3, 4, 9, 10, 11, 12, 13, 14, 16, 23, 24):
    KIND_BY_NUMBER[_n] = KIND_CHOICE
for _n in (15, 17, 18, 19, 20, 21, 26):
    KIND_BY_NUMBER[_n] = KIND_DIGITS
for _n in (8, 22):
    KIND_BY_NUMBER[_n] = KIND_MATCH
del _n

assert set(KIND_BY_NUMBER) == set(TASK_NUMBERS), "таблица видов не покрывает все номера"


def kind_of(number: int) -> str | None:
    """Вид задания по его номеру. None — номера нет в работе."""
    return KIND_BY_NUMBER.get(number)

